DROP TABLE IF EXISTS fee_transaction_details;
DROP TABLE IF EXISTS fee_transactions;
DROP TABLE IF EXISTS admissions;
DROP TABLE IF EXISTS students;
DROP TABLE IF EXISTS programs;
DROP TABLE IF EXISTS departments;

CREATE TABLE departments (
    department_id   INT PRIMARY KEY,
    department_name VARCHAR(100) NOT NULL
);

CREATE TABLE programs (
    program_id      INT PRIMARY KEY,
    program_name    VARCHAR(100) NOT NULL,
    department_id   INT NOT NULL,
    duration_years  INT NOT NULL,
    total_fee       DECIMAL(12,2) NOT NULL,
    FOREIGN KEY (department_id) REFERENCES departments(department_id)
);

CREATE TABLE students (
    student_id      INT PRIMARY KEY,
    admission_no    VARCHAR(20) NOT NULL,
    full_name       VARCHAR(150) NOT NULL,
    program_id      INT NOT NULL,
    department_id   INT NOT NULL,
    admission_year  INT NOT NULL,
    email           VARCHAR(150),
    phone           VARCHAR(15),
    FOREIGN KEY (program_id) REFERENCES programs(program_id),
    FOREIGN KEY (department_id) REFERENCES departments(department_id)
);

CREATE TABLE admissions (
    admission_id    INT PRIMARY KEY,
    admission_no    VARCHAR(20) NOT NULL,
    admission_date  DATE NOT NULL,
    status          VARCHAR(20) NOT NULL
);

CREATE TABLE fee_transactions (
    transaction_id   INT PRIMARY KEY,
    admission_no     VARCHAR(20) NOT NULL,
    transaction_date DATE NOT NULL,
    transaction_type VARCHAR(20) NOT NULL,   -- DUE / PAID / CONCESSION
    total_amount     DECIMAL(12,2) NOT NULL,
    status           VARCHAR(20) NOT NULL
);

CREATE TABLE fee_transaction_details (
    detail_id       INT PRIMARY KEY,
    transaction_id  INT NOT NULL,            -- NOTE: intentionally NOT declared as a foreign key here;
    admission_no    VARCHAR(20) NOT NULL,     -- part of the assignment is finding rows that violate this relationship
    fee_head        VARCHAR(50) NOT NULL,
    amount          DECIMAL(12,2) NOT NULL,
    status          VARCHAR(20) NOT NULL
);

